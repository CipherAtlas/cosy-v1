export function villageName(name: string, language: "en" | "ja") {
  return language === "ja" ? JAPANESE_NAMES[name] ?? name : name;
}

export function villageNotice(message: string, language: "en" | "ja") {
  if (language !== "ja") return message;
  if (JAPANESE_NOTICES[message]) return JAPANESE_NOTICES[message];
  const crop = /^This farm only grows (carrot|radish|mint)\.$/.exec(message)?.[1];
  if (crop) return `この畑では${({ carrot: "ニンジン", radish: "ラディッシュ", mint: "ミント" } as Record<string, string>)[crop]}だけを育てられます。`;
  const food = /^Your basket has no (apple|mushroom)\. Pick an apple or receive a hedgehog gift first\.$/.exec(message)?.[1];
  if (food) return `かごに${food === "apple" ? "リンゴ" : "キノコ"}がありません。リンゴを摘むか、ハリネズミのおみやげを受け取りましょう。`;
  return message;
}

export function preferredVillageLanguage(saved: unknown, browserLanguage: string): "en" | "ja" {
  return saved === "en" || saved === "ja" ? saved : /^ja(?:-|$)/i.test(browserLanguage) ? "ja" : "en";
}

/** Used after mount, including the lightweight entry and moderation screens. */
export function readVillageLanguage() {
  let saved: unknown;
  try { saved = JSON.parse(localStorage.getItem("cosy-village-preferences") || "null")?.language; } catch {}
  return preferredVillageLanguage(saved, navigator.language);
}
